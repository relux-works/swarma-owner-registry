//go:build linux

package store

import (
	"bytes"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func decode(raw []byte, v any) bool {
	return json.Unmarshal(raw, v) == nil && bytes.Equal(raw, canonical(v))
}
func (s *Store) materialize(next image, stateID string) error {
	paths := make([]string, 0, len(next.Files))
	for path := range next.Files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		if e := s.disk.atomic(path, next.Files[path], stateID, false); e != nil {
			return e
		}
	}
	return nil
}
func allowedDirectory(p string) bool {
	for _, v := range layoutDirs() {
		if p == v+"/" {
			return true
		}
	}
	return false
}
func temporaryOwner(path string) (string, bool) {
	name := filepath.Base(path)
	if !strings.HasPrefix(name, ".tmp-") || len(name) < 5+64+1+1 || name[69] != '-' {
		return "", false
	}
	id := "sha256:" + name[5:69]
	if !validID(id) {
		return "", false
	}
	// Suffixes are generated by crypto/rand.Text, never caller supplied paths.
	for _, c := range name[70:] {
		if !(c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9') {
			return "", false
		}
	}
	return id, true
}
func (s *Store) inventory(paths []string, files map[string][]byte, manifests map[string]bool, anchorID string) error {
	for _, p := range paths {
		if strings.HasSuffix(p, "/") {
			if !allowedDirectory(p) {
				return errors.New("unknown directory")
			}
			continue
		}
		if p == "anchor.json" || p == "CURRENT" {
			continue
		}
		if owner, ok := temporaryOwner(p); ok {
			if !manifests[owner] && owner != anchorID {
				return errors.New("incomplete candidate manifest")
			}
			parent := filepath.Dir(p)
			if parent != "." && !allowedDirectory(parent+"/") {
				return errors.New("unknown staging directory")
			}
			continue
		}
		if strings.HasPrefix(p, "transactions/") && strings.HasSuffix(p, ".json") {
			id := strings.TrimSuffix(strings.TrimPrefix(p, "transactions/"), ".json")
			if validID(id) && manifests[id] {
				continue
			}
		}
		if _, ok := files[p]; !ok {
			return errors.New("unreferenced local evidence")
		}
	}
	return nil
}
func (s *Store) audit() error {
	paths, e := s.disk.scan()
	if e != nil {
		return e
	}
	if e = s.inventory(paths, s.active.Files, s.manifests, digest(genesis())); e != nil {
		return e
	}
	raw, e := s.disk.read("anchor.json")
	if e != nil || !bytes.Equal(raw, canonical(genesis())) {
		return errors.New("missing anchor")
	}
	raw, e = s.disk.read("CURRENT")
	if e != nil || !bytes.Equal(raw, []byte(s.stateID+"\n")) {
		return errors.New("unresolved head")
	}
	for p, want := range s.active.Files {
		b, e := s.disk.read(p)
		if e != nil || !bytes.Equal(b, want) {
			return errors.New("authoritative bytes unavailable")
		}
	}
	// Retained complete manifests are authoritative evidence too.
	for stateID := range s.manifests {
		b, e := s.disk.read("transactions/" + stateID + ".json")
		var m manifest
		if e != nil || !bytes.Equal(b, s.manifestBytes[stateID]) || !decode(b, &m) || digest(m.Candidate) != stateID {
			return errors.New("manifest unavailable")
		}
	}
	return nil
}

// Reconcile retains every candidate/fragment, validates the complete lineage
// and recovers only its exact latest complete image. Missing or ambiguous
// candidate evidence stays fenced; an earlier CURRENT never cancels an intent.
func (s *Store) Reconcile(expectedStateID string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.fenced = true
	if s.closed || !validID(expectedStateID) || (s.pendingID != "" && s.pendingID != expectedStateID) {
		return refuse(StateUnavailable)
	}
	paths, e := s.disk.scan()
	if e != nil {
		return refuse(StateUnavailable)
	}
	raw, e := s.disk.read("anchor.json")
	if e != nil || !bytes.Equal(raw, canonical(genesis())) {
		return refuse(StateUnavailable)
	}
	byBase := map[string]manifest{}
	ids := map[string]bool{}
	manifestBytes := map[string][]byte{}
	for _, p := range paths {
		if !strings.HasPrefix(p, "transactions/") || !strings.HasSuffix(p, ".json") {
			continue
		}
		stateID := strings.TrimSuffix(strings.TrimPrefix(p, "transactions/"), ".json")
		raw, e = s.disk.read(p)
		var m manifest
		if e != nil || !decode(raw, &m) || !validID(stateID) || digest(m.Candidate) != stateID || !validID(m.Base) {
			return refuse(StateUnavailable)
		}
		if _, ok := byBase[m.Base]; ok {
			return refuse(StateUnavailable)
		}
		byBase[m.Base] = m
		ids[stateID] = true
		manifestBytes[stateID] = append([]byte{}, raw...)
	}
	next := genesis()
	stateID := digest(next)
	visited := map[string]bool{stateID: true}
	for {
		m, ok := byBase[stateID]
		if !ok {
			break
		}
		if validate(m.Request) != nil {
			return refuse(StateUnavailable)
		}
		expected, _, err := candidate(next, m.Request)
		if err != nil || expected.Files == nil || !bytes.Equal(canonical(expected), canonical(m.Candidate)) {
			return refuse(StateUnavailable)
		}
		next = m.Candidate
		stateID = digest(next)
		if visited[stateID] {
			return refuse(StateUnavailable)
		}
		visited[stateID] = true
	}
	if stateID != expectedStateID {
		return refuse(StateUnavailable)
	}
	if len(visited) != len(ids)+1 {
		return refuse(StateUnavailable)
	}
	if e = s.inventory(paths, next.Files, ids, digest(genesis())); e != nil {
		return refuse(StateUnavailable)
	}
	current, e := s.disk.read("CURRENT")
	if e == nil {
		old := strings.TrimSuffix(string(current), "\n")
		if !bytes.Equal(current, []byte(old+"\n")) || !visited[old] {
			return refuse(StateUnavailable)
		}
	} else if !errors.Is(e, os.ErrNotExist) || len(ids) == 0 {
		return refuse(StateUnavailable)
	}
	for id := range ids {
		if e = s.disk.resync("transactions/" + id + ".json"); e != nil {
			return refuse(StateUnavailable)
		}
	}
	if e = s.materialize(next, stateID); e != nil {
		return refuse(StateUnavailable)
	}
	for path := range next.Files {
		if e = s.disk.resync(path); e != nil {
			return refuse(StateUnavailable)
		}
	}

	if e = s.disk.atomic("CURRENT", []byte(stateID+"\n"), stateID, true); e != nil {
		return refuse(StateUnavailable)
	}
	if e = s.disk.resync("CURRENT"); e != nil {
		return refuse(StateUnavailable)
	}
	s.active, s.stateID, s.manifests = next, stateID, ids
	s.manifestBytes = manifestBytes
	s.pendingID = ""
	s.fenced = false
	return nil
}
